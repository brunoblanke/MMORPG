// js/controllers/particle-controller.js

import { ParticleSystem } from '../services/particle-system.js';

export class ParticleController {
  constructor() {
    this.particleSystem = new ParticleSystem();
  }

  // ================================================================================================================================================================================================================================================
  // spawnDamage

  spawnDamage(x, y, damage, renderer) {
    this.particleSystem.spawnDamageNumber(x, y, damage, false, renderer);
  }

  // ================================================================================================================================================================================================================================================
  // spawnXP

  spawnXP(x, y, xp, renderer) {
    this.particleSystem.spawnDamageNumber(x, y, xp, true, renderer);
  }

  // ================================================================================================================================================================================================================================================
  // update

  update(timestamp) {
    this.particleSystem.update(timestamp);
  }

  // ================================================================================================================================================================================================================================================
  // render

  render(ctx) {
    this.particleSystem.render(ctx);
  }

  // ================================================================================================================================================================================================================================================
  // clear

  clear() {
    this.particleSystem.clear();
  }
}