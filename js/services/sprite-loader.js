// js/services/sprite-loader.js

import { loadImage, loadAllImages, getCachedImage } from '../../shared/image-loader.js';

export class SpriteLoader {
  // ================================================================================================================================================================================================================================================
  // load

  load(url) {
    return loadImage(url).promise;
  }

  // ================================================================================================================================================================================================================================================
  // loadAll

  loadAll(spriteList, onProgress = null) {
    return loadAllImages(spriteList, onProgress);
  }

  // ================================================================================================================================================================================================================================================
  // get

  get(url) {
    const entry = getCachedImage(url);
    return entry ? entry.img : null;
  }
}