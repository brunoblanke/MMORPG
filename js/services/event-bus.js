// event-bus.js

export class EventBus {
  constructor() {
    this.events = {};
  }

  // ================================================================================================================================================================================================================================================
  // on

  on(event, callback) {
    if (!this.events[event]) {
      this.events[event] = [];
    }
    this.events[event].push(callback);
  }

  // ================================================================================================================================================================================================================================================
  // off

  off(event, callback) {
    if (!this.events[event]) return;
    this.events[event] = this.events[event].filter(cb => cb !== callback);
  }

  // ================================================================================================================================================================================================================================================
  // emit

  emit(event, data) {
    if (!this.events[event]) return;
    for (const callback of this.events[event]) {
      callback(data);
    }
  }

  // ================================================================================================================================================================================================================================================
  // clear

  clear() {
    this.events = {};
  }
}